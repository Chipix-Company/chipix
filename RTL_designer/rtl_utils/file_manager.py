"""
Automatic file management for the RTL Design Agent.
Creates project directories, writes RTL files, and manages the workspace —
just like Cursor/Antigravity auto-creates files.
"""

from __future__ import annotations
import os
import re
import json
from datetime import datetime
from pathlib import Path
from dataclasses import dataclass, field, asdict


@dataclass
class FileAction:
    """Represents a single file creation/modification action."""
    action: str         # "created", "modified", "deleted"
    filepath: str       # absolute path
    filename: str       # just the name
    module_name: str    # RTL module name
    lines: int          # number of lines
    timestamp: str      # ISO timestamp


@dataclass
class ProjectWorkspace:
    """Manages the auto-created project workspace."""
    root_dir: str
    project_name: str
    files: list[FileAction] = field(default_factory=list)
    structure: dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        return {
            "root_dir": self.root_dir,
            "project_name": self.project_name,
            "files": [asdict(f) for f in self.files],
            "structure": self.structure,
        }


def create_project_workspace(base_dir: str, project_name: str) -> ProjectWorkspace:
    """
    Create a full project directory structure for an RTL design.
    Similar to how Cursor scaffolds a project.
    
    Structure:
      <project_name>/
        ├── rtl/           # RTL source files
        ├── tb/            # Testbench files
        ├── docs/          # Documentation
        ├── sim/           # Simulation scripts
        └── README.md      # Auto-generated README
    """
    # Clean project name
    clean_name = re.sub(r'[^\w\-]', '_', project_name.lower().strip())
    project_dir = os.path.join(base_dir, clean_name)

    # Create directory structure
    dirs = {
        "root": project_dir,
        "rtl": os.path.join(project_dir, "rtl"),
        "tb": os.path.join(project_dir, "tb"),
        "docs": os.path.join(project_dir, "docs"),
        "sim": os.path.join(project_dir, "sim"),
    }

    for d in dirs.values():
        os.makedirs(d, exist_ok=True)

    workspace = ProjectWorkspace(
        root_dir=project_dir,
        project_name=clean_name,
        structure=dirs,
    )

    return workspace


def write_rtl_file(
    workspace: ProjectWorkspace,
    code: str,
    module_name: str,
    language: str = "verilog",
) -> FileAction:
    """
    Write a single RTL module to a file in the workspace.
    Auto-detects module name if not provided.
    Returns a FileAction describing what was done.
    """
    ext = ".sv" if language == "systemverilog" else ".v"
    filename = f"{module_name}{ext}"
    filepath = os.path.join(workspace.structure["rtl"], filename)

    # Write the file
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(code)

    lines = code.count("\n") + 1
    action = FileAction(
        action="created",
        filepath=filepath,
        filename=filename,
        module_name=module_name,
        lines=lines,
        timestamp=datetime.now().isoformat(),
    )
    workspace.files.append(action)
    return action


def write_composed_file(
    workspace: ProjectWorkspace,
    code: str,
    project_name: str,
    language: str = "verilog",
) -> FileAction:
    """
    Write the full composed design (all modules in one file) to the workspace.
    """
    ext = ".sv" if language == "systemverilog" else ".v"
    filename = f"{project_name}_top{ext}"
    filepath = os.path.join(workspace.structure["rtl"], filename)

    with open(filepath, "w", encoding="utf-8") as f:
        f.write(code)

    lines = code.count("\n") + 1
    action = FileAction(
        action="created",
        filepath=filepath,
        filename=filename,
        module_name=f"{project_name}_top",
        lines=lines,
        timestamp=datetime.now().isoformat(),
    )
    workspace.files.append(action)
    return action


def write_readme(workspace: ProjectWorkspace, spec: str, language: str) -> FileAction:
    """Auto-generate a README.md for the project."""
    lang_label = "SystemVerilog" if language == "systemverilog" else "Verilog"

    # List RTL files
    rtl_files = [f for f in workspace.files if f.filepath.endswith(('.v', '.sv'))]
    file_list = "\n".join(f"  - `{f.filename}` — {f.module_name} ({f.lines} lines)" for f in rtl_files)
    total_lines = sum(f.lines for f in rtl_files)

    readme = f"""# {workspace.project_name}

> Auto-generated by **RTL Design Agent** on {datetime.now().strftime('%Y-%m-%d %H:%M')}

## Overview
Language: **{lang_label}**
Total RTL Lines: **{total_lines}**
Files: **{len(rtl_files)}**

## File Structure
```
{workspace.project_name}/
├── rtl/           # RTL source files
│   {chr(10).join('├── ' + f.filename for f in rtl_files)}
├── tb/            # Testbench files (todo)
├── docs/          # Documentation
├── sim/           # Simulation scripts
└── README.md
```

## RTL Files
{file_list}

## Specification
{spec}
"""

    filepath = os.path.join(workspace.root_dir, "README.md")
    with open(filepath, "w", encoding="utf-8") as f:
        f.write(readme)

    action = FileAction(
        action="created",
        filepath=filepath,
        filename="README.md",
        module_name="documentation",
        lines=readme.count("\n") + 1,
        timestamp=datetime.now().isoformat(),
    )
    workspace.files.append(action)
    return action


