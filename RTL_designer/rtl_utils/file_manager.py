def extract_all_modules(code: str) -> list[tuple[str, str]]:
    """
    Extract individual modules from a combined RTL file.
    Returns list of (module_name, module_code) tuples.
    """
    # First strip markdown code blocks
    code_match = re.search(r"```(?:verilog|systemverilog|sv)?\s*\n(.*?)```", code, re.DOTALL)
    if code_match:
        code = code_match.group(1)

    modules = []
    # Find each module...endmodule block including any preceding comments
    pattern = r"((?://[^\n]*\n)*\s*module\s+(\w+)[\s\S]*?endmodule)"
    for match in re.finditer(pattern, code):
        full_code = match.group(1).strip()
        name = match.group(2)
        modules.append((name, full_code))

    return modules


def auto_write_all_files(
    workspace: ProjectWorkspace,
    rtl_code: str,
    spec: str,
    language: str,
) -> list[FileAction]:
    """
    Master function: automatically extract all modules from the generated code
    and write each one to its own file + testbench stubs + README.
    This is the "Cursor-like" auto-file-creation experience.
    """
    all_actions = []

    # 1) Extract individual modules
    modules = extract_all_modules(rtl_code)

    if modules:
        # Write each module to its own file
        for mod_name, mod_code in modules:
            action = write_rtl_file(workspace, mod_code, mod_name, language)
            all_actions.append(action)

        # Write the full combined file too
        code_match = re.search(r"```(?:verilog|systemverilog|sv)?\s*\n(.*?)```", rtl_code, re.DOTALL)
        full_code = code_match.group(1).strip() if code_match else rtl_code.strip()
        combined_action = write_composed_file(workspace, full_code, workspace.project_name, language)
        all_actions.append(combined_action)

        # Write testbench stubs for each module
        for mod_name, _ in modules:
            tb_action = write_testbench_stub(workspace, mod_name, "", language)
            all_actions.append(tb_action)
    else:
        # Single block of code, no module detected — write as-is
        code_match = re.search(r"```(?:verilog|systemverilog|sv)?\s*\n(.*?)```", rtl_code, re.DOTALL)
        clean_code = code_match.group(1).strip() if code_match else rtl_code.strip()
        action = write_rtl_file(workspace, clean_code, workspace.project_name, language)
        all_actions.append(action)

    # 2) Write README
    readme_action = write_readme(workspace, spec, language)
    all_actions.append(readme_action)

    # 3) Write project manifest
    manifest = {
        "project": workspace.project_name,
        "language": language,
        "generated_at": datetime.now().isoformat(),
        "files": [asdict(a) for a in all_actions],
        "total_lines": sum(a.lines for a in all_actions),
    }
    manifest_path = os.path.join(workspace.root_dir, "project.json")
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)

    return all_actions


def format_file_tree(workspace: ProjectWorkspace) -> str:
    """
    Generate a pretty file tree string showing all created files,
    similar to what Cursor shows in its file panel.
    """
    lines = [f"📁 **{workspace.project_name}/**"]

    # Group files by directory
    by_dir: dict[str, list[FileAction]] = {}
    for fa in workspace.files:
        parent = os.path.dirname(fa.filepath)
        rel = os.path.relpath(parent, workspace.root_dir)
        if rel == ".":
            rel = ""
        if rel not in by_dir:
            by_dir[rel] = []
        by_dir[rel].append(fa)

    # Sort directories
    for dir_name in sorted(by_dir.keys()):
        files = by_dir[dir_name]
        if dir_name:
            icon = "📂"
            if "rtl" in dir_name:
                icon = "🔧"
            elif "tb" in dir_name:
                icon = "🧪"
            elif "docs" in dir_name:
                icon = "📄"
            lines.append(f"├── {icon} **{dir_name}/**")
            prefix = "│   "
        else:
            prefix = "├── "

        for i, fa in enumerate(files):
            is_last = (i == len(files) - 1)
            connector = "└──" if is_last else "├──"

            # File icon based on extension
            if fa.filename.endswith(('.v', '.sv')):
                if fa.filename.startswith('tb_'):
                    ficon = "🧪"
                else:
                    ficon = "📝"
            elif fa.filename.endswith('.md'):
                ficon = "📄"
            else:
                ficon = "📎"

            status_icon = "✅" if fa.action == "created" else "📝"
            lines.append(
                f"{prefix}{connector} {ficon} `{fa.filename}` "
                f"({fa.lines} lines) {status_icon}"
            )

    return "\n".join(lines)
